#!/usr/bin/env python3
"""LED resistor, current, runtime and charge-current calculations.

Every assumption is a named constant so it can be replaced by a bench
measurement.  Run:  python3 led_power_calc.py > led_power_results.md
"""

# ---------------- assumptions (replace with measurements) ----------------
CELL_CAPACITY_MAH = 30.0      # nominal, 301012-class LiPo with PCM (PROVISIONAL)
USABLE_FRACTION   = 0.80      # PCM cut-off + derating + diode-limited charge (see below)
V_CELL = {"full (diode-limited)": 3.95, "nominal": 3.70, "low": 3.40, "cut-off region": 3.10}
# Green InGaN 0603 LED (e.g. Kingbright APTD1608LZGCK). Datasheet gives Vf at 20 mA;
# at 1–3 mA Vf is lower.  2.75 V @ ~1.5 mA is an ESTIMATE -> measure (test LED-01).
VF_LOW_CURRENT = 2.75
VF_SLOPE_OHM   = 60.0         # small-signal dynamic resistance estimate
N_LED = 3
R_OPTIONS = [330, 470, 680, 1000, 1500]  # E12 values, one resistor per LED
PROT_IQ_UA = 3.0              # typical PCM quiescent current (DW01-class), verify
SWITCH_OFF_LEAK_UA = 0.0

# Charger (in cradle): MCP73831, I_REG(mA) = 1000 / R_PROG(kΩ), range 15–500 mA
R_PROG_KOHM = 66.5   # E96; gives ~15.0 mA (device minimum 15 mA)
DIODE_VF_AT_TERMINATION = 0.25  # BAT54-class Schottky at ~1 mA (verify)


def led_current(v_cell, r):
    # solve I = (V - Vf(I)) / R with Vf(I) = VF0 + I*rd  (linear model around 1–3 mA)
    i = (v_cell - VF_LOW_CURRENT) / (r + VF_SLOPE_OHM)
    return max(i, 0.0)


def main():
    print("# LED & power calculations (generated by led_power_calc.py)\n")
    print("Model: I = (V_cell − Vf) / (R + r_d), Vf = %.2f V (estimate at ~1.5 mA), "
          "r_d = %.0f Ω, %d LEDs each with its own resistor.\n" % (VF_LOW_CURRENT, VF_SLOPE_OHM, N_LED))
    print("## Per-LED current (mA) vs cell voltage and resistor\n")
    print("| R (Ω) | " + " | ".join(f"{k} {v:.2f} V" for k, v in V_CELL.items()) + " | P_R max (mW) |")
    print("|---|" + "---|" * (len(V_CELL) + 1))
    for r in R_OPTIONS:
        cur = [led_current(v, r) * 1e3 for v in V_CELL.values()]
        pmax = (max(cur) / 1e3) ** 2 * r * 1e3
        print(f"| {r} | " + " | ".join(f"{c:.2f}" for c in cur) + f" | {pmax:.3f} |")

    print("\n## Runtime estimate (all LEDs on)\n")
    usable = CELL_CAPACITY_MAH * USABLE_FRACTION
    print(f"Usable capacity assumed: {CELL_CAPACITY_MAH:.0f} mAh × {USABLE_FRACTION:.2f} = {usable:.1f} mAh\n")
    print("| R (Ω) | total current @3.7 V (mA) | runtime (h) | LED power (mW) |")
    print("|---|---|---|---|")
    for r in R_OPTIONS:
        i_tot = N_LED * led_current(V_CELL["nominal"], r) * 1e3 + PROT_IQ_UA / 1e3
        print(f"| {r} | {i_tot:.2f} | {usable / i_tot:.1f} | {i_tot * V_CELL['nominal']:.1f} |")

    off_ua = PROT_IQ_UA + SWITCH_OFF_LEAK_UA
    print(f"\nStandby drain with switch OFF ≈ {off_ua:.1f} µA → {usable * 1e3 / off_ua / 24:.0f} days "
          f"from full (self-discharge of the cell will dominate; recharge monthly).\n")

    i_chg = 1000.0 / R_PROG_KOHM
    print("## Charging (charger lives in the cradle)\n")
    print(f"* MCP73831 R_PROG = {R_PROG_KOHM:.1f} kΩ → I_REG = 1000/{R_PROG_KOHM:.1f} = **{i_chg:.1f} mA** "
          f"(device minimum is 15 mA).")
    print(f"* C-rate for a {CELL_CAPACITY_MAH:.0f} mAh cell = {i_chg / CELL_CAPACITY_MAH:.2f} C "
          "(must be ≤ the cell's max charge rate, typically 0.5–1 C; check the cell datasheet).")
    print("* **Do not use a cell smaller than ~%d mAh** with this charger setting (would exceed 0.5 C)." % (i_chg / 0.5 + 0.5))
    print(f"* Series Schottky in the ring (reverse-short protection on the exposed contacts) "
          f"means the cell terminates near 4.20 − {DIODE_VF_AT_TERMINATION:.2f} ≈ "
          f"{4.20 - DIODE_VF_AT_TERMINATION:.2f} V (~80–85 % capacity). This is deliberately conservative.")
    t_cc = CELL_CAPACITY_MAH * 0.85 / i_chg
    print(f"* Approx. charge time from empty: CC phase ≈ {t_cc:.1f} h + CV taper ≈ 0.5–1 h → **~{t_cc + 0.75:.1f} h**.")
    print(f"* Datasheet termination/preconditioning tables are specified for R_PROG 2–10 kΩ; at {R_PROG_KOHM:.1f} kΩ "
          "termination behaviour must be verified on the bench (test CHG-02).")


if __name__ == "__main__":
    main()
