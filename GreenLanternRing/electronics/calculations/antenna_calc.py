#!/usr/bin/env python3
"""13.56 MHz antenna estimates for NON-PAYMENT experiments (Phase 2).

These are first-order textbook approximations (±20–30 %). They tell you
roughly how many turns to wind so a test coil lands near resonance with a
known tag chip's input capacitance.  Always confirm with a measurement
(NanoVNA or reader read-range); never use these numbers to "retune" a bank
card or payment module.

Formulas
  * Multi-turn circular loop (bundle):  L ≈ μ0 · N² · r · [ln(8r/a) − 2]
        r = loop radius, a = radius of the wire bundle
  * Flat circular spiral (Mohan current-sheet):
        L ≈ μ0 · N² · d_avg · c1/2 · [ln(c2/ρ) + c3·ρ + c4·ρ²],
        circular: c1 = 1.00, c2 = 2.46, c3 = 0, c4 = 0.20
        d_avg = (d_out + d_in)/2,  ρ = (d_out − d_in)/(d_out + d_in)
  * Resonance:  f = 1 / (2π √(L·C))  →  L_target = 1 / ((2πf)² · C)
Run:  python3 antenna_calc.py > antenna_results.md
"""
import math

MU0 = 4e-7 * math.pi
F = 13.56e6

# Chip input capacitances from public NXP datasheets (non-payment chips).
CHIPS = {
    "NTAG213/215/216 (Ci = 50 pF)": 50e-12,
    "MIFARE Classic EV1 (Ci = 17 pF)": 17e-12,
}


def loop_L(N, r, wire_d, bundle_fill=0.7):
    # approximate bundle radius from N round wires packed with given fill
    a = math.sqrt(N * (wire_d / 2) ** 2 / bundle_fill)
    return MU0 * N ** 2 * r * (math.log(8 * r / a) - 2)


def spiral_L(N, d_out, d_in):
    davg = (d_out + d_in) / 2
    rho = (d_out - d_in) / (d_out + d_in)
    return MU0 * N ** 2 * davg * 0.5 * (math.log(2.46 / rho) + 0.20 * rho ** 2)


def L_target(C):
    return 1 / ((2 * math.pi * F) ** 2 * C)


def main():
    print("# Antenna estimates (generated by antenna_calc.py)\n")
    print("Target inductance for resonance at 13.56 MHz (ignoring coil self-capacitance, "
          "which pushes the real optimum ~5–15 % lower):\n")
    for k, c in CHIPS.items():
        print(f"* {k}: **L ≈ {L_target(c) * 1e6:.2f} µH**")

    print("\n## 1. Coil wound round the ring band\n")
    for finger_d in (18.0, 19.0, 20.0):
        r = (finger_d + 2 * 1.0) / 2 / 1000  # channel sits ~1 mm outside the finger bore
        print(f"\nFinger Ø {finger_d} mm → loop radius ≈ {r * 1000:.1f} mm, 0.20 mm enamelled wire (≈ 32 AWG)\n")
        print("| N turns | L (µH) | f_res with 50 pF (MHz) | f_res with 17 pF (MHz) |")
        print("|---|---|---|---|")
        for N in range(3, 15):
            L = loop_L(N, r, 0.20e-3)
            f50 = 1 / (2 * math.pi * math.sqrt(L * 50e-12)) / 1e6
            f17 = 1 / (2 * math.pi * math.sqrt(L * 17e-12)) / 1e6
            print(f"| {N} | {L * 1e6:.2f} | {f50:.1f} | {f17:.1f} |")

    print("\n## 2. Flat spiral under the emblem\n")
    for d_out in (12.0, 14.0, 16.0):
        print(f"\nOuter Ø {d_out} mm, track/wire pitch 0.30 mm\n")
        print("| N turns | inner Ø (mm) | L (µH) | f_res with 50 pF (MHz) |")
        print("|---|---|---|---|")
        for N in range(4, 16, 2):
            d_in = d_out - 2 * N * 0.30
            if d_in <= 2:
                break
            L = spiral_L(N, d_out / 1000, d_in / 1000)
            f50 = 1 / (2 * math.pi * math.sqrt(L * 50e-12)) / 1e6
            print(f"| {N} | {d_in:.1f} | {L * 1e6:.2f} | {f50:.1f} |")

    print("\n## Reading the tables\n")
    print("* Pick the N whose f_res is closest to 13.56 MHz (slightly above is better: "
          "self-capacitance and nearby plastic/skin pull it down).")
    print("* Coupling (k) to the reader falls steeply as the coil gets smaller than the reader "
          "antenna; a ~20 mm coil reads at a few mm to ~2 cm, versus ~4 cm for a card.")
    print("* Metal (battery can, PCB copper pour) within a few mm lowers L and Q; "
          "a ferrite sheet between coil and metal recovers much of it.")


if __name__ == "__main__":
    main()
